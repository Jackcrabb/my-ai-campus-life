import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import vm from 'node:vm';
import { planVoices, estimate, validateProviderVoices } from '../scripts/generate-voices.mjs';

const cast = JSON.parse(await readFile(new URL('../data/voice-cast.json', import.meta.url)));
const corpus = JSON.parse(await readFile(new URL('../data/voice-auditions.json', import.meta.url)));
const context = vm.createContext({ window: {} });
vm.runInContext(await readFile(new URL('../public/campus/characters.js', import.meta.url), 'utf8'), context);
const plan = planVoices(cast, corpus);
assert.equal(Object.keys(cast.characters).length, 20);
for (const id of Object.keys(cast.characters)) assert.equal(context.window.CAMPUS_CHARACTERS.resolve(id)?.id, id, `Unknown character: ${id}`);
assert.equal(new Set(corpus.lines.map(line => line.characterId)).size, 20);
assert.equal(plan.length, 60);
assert.equal(new Set(plan.map(item => item.file)).size, 60);
assert.equal(new Set(plan.map(item => item.request.voice.name)).size, 60);
for (const locale of ['zh', 'cn', 'en']) assert.equal(plan.filter(item => item.locale === locale).length, 20);
assert.ok(plan.filter(item => item.locale === 'cn').every(item => item.request.voice.languageCode === 'cmn-CN' && item.request.voice.name.startsWith('cmn-CN-')));
assert.ok(plan.filter(item => item.locale === 'zh').every(item => item.request.voice.languageCode === 'yue-HK' && item.request.voice.name.startsWith('yue-HK-')));
assert.ok(plan.every(item => item.request.input.text === item.text && item.request.audioConfig.speakingRate === 1));
const available = plan.map(item => ({ name: item.request.voice.name, languageCodes: [item.request.voice.languageCode] }));
validateProviderVoices(plan, available);
assert.throws(() => validateProviderVoices(plan, available.slice(1)), /no substitute/);
const wrongLanguage = structuredClone(available); wrongLanguage[1].languageCodes = ['yue-HK'];
assert.throws(() => validateProviderVoices(plan, wrongLanguage), /no substitute/);
const changedText = structuredClone(corpus); changedText.lines[0].text.cn += '請重試。';
const changedPlan = planVoices(cast, changedText);
assert.equal(plan[0].fingerprint, changedPlan[0].fingerprint);
assert.notEqual(plan[1].fingerprint, changedPlan[1].fingerprint);
assert.notEqual(plan[1].file, changedPlan[1].file);
const badCast = structuredClone(cast); badCast.locales.cn = 'yue-HK';
assert.throws(() => planVoices(badCast, corpus), /locale mapping/);
const duplicate = structuredClone(corpus); duplicate.lines.push(duplicate.lines[0]);
assert.throws(() => planVoices(cast, duplicate), /duplicate line ID/);
const badPath = structuredClone(corpus); badPath.lines[0].id = '../escape';
assert.throws(() => planVoices(cast, badPath), /line ID/);
const missing = structuredClone(corpus); delete missing.lines[0].text.cn;
assert.throws(() => planVoices(cast, missing), /Missing/);
assert.equal(estimate(plan).characters, plan.reduce((sum, item) => sum + [...item.text].length, 0));
console.log(`Voice generation: ${plan.length} explicit-locale auditions, 20 unique voices, locale/cast/corpus validation and revision invalidation passed. No synthesis API called.`);
